-- 1. Aggregate Functions

-- COUNT(): Total number of orders
SELECT COUNT(ORDER_ID) AS TOTAL_ORDERS
FROM ORDERS;

-- SUM(): Total quantity ordered
SELECT SUM(QUANTITY) AS TOTAL_QUANTITY
FROM ORDERS;

-- AVG(): Average order amount
SELECT AVG(ORDER_AMOUNT) AS AVERAGE_ORDER_AMOUNT
FROM (
    SELECT O.ORDER_ID,
           SUM(O.QUANTITY * P.PRICE) AS ORDER_AMOUNT
    FROM ORDERS O
    JOIN PRODUCT P
      ON O.PRODUCT_ID = P.PRODUCT_ID
    GROUP BY O.ORDER_ID
);

-- MIN(): Minimum order amount
SELECT MIN(ORDER_AMOUNT) AS MINIMUM_ORDER_AMOUNT
FROM (
    SELECT O.ORDER_ID,
           SUM(O.QUANTITY * P.PRICE) AS ORDER_AMOUNT
    FROM ORDERS O
    JOIN PRODUCT P
      ON O.PRODUCT_ID = P.PRODUCT_ID
    GROUP BY O.ORDER_ID
);

-- MAX(): Maximum order amount
SELECT MAX(ORDER_AMOUNT) AS MAXIMUM_ORDER_AMOUNT
FROM (
    SELECT O.ORDER_ID,
           SUM(O.QUANTITY * P.PRICE) AS ORDER_AMOUNT
    FROM ORDERS O
    JOIN PRODUCT P
      ON O.PRODUCT_ID = P.PRODUCT_ID
    GROUP BY O.ORDER_ID
);

-- 2. Generate Total Sales Reports

-- Total sales
SELECT SUM(O.QUANTITY * P.PRICE) AS TOTAL_SALES
FROM ORDERS O
JOIN PRODUCT P
  ON O.PRODUCT_ID = P.PRODUCT_ID;

-- Customer-wise Sales Report
SELECT C.CUSTOMER_ID,
       C.CUSTOMER_NAME,
       SUM(O.QUANTITY * P.PRICE) AS TOTAL_PURCHASE
FROM CUSTOMERS C
JOIN ORDERS O
  ON C.CUSTOMER_ID = O.CUSTOMER_ID
JOIN PRODUCT P
  ON O.PRODUCT_ID = P.PRODUCT_ID
GROUP BY C.CUSTOMER_ID, C.CUSTOMER_NAME
ORDER BY TOTAL_PURCHASE DESC;

-- Customers Based on Purchase Amount (Top 5)
SELECT C.CUSTOMER_ID,
       C.CUSTOMER_NAME,
       SUM(O.QUANTITY * P.PRICE) AS TOTAL_PURCHASE
FROM CUSTOMERS C
JOIN ORDERS O
  ON C.CUSTOMER_ID = O.CUSTOMER_ID
JOIN PRODUCT P
  ON O.PRODUCT_ID = P.PRODUCT_ID
GROUP BY C.CUSTOMER_ID, C.CUSTOMER_NAME
ORDER BY TOTAL_PURCHASE DESC
FETCH FIRST 5 ROWS ONLY;

-- Identify Best-Selling Products
SELECT P.PRODUCT_ID,
       P.PRODUCT_NAME,
       SUM(O.QUANTITY) AS TOTAL_QUANTITY_SOLD
FROM PRODUCT P
JOIN ORDERS O
  ON P.PRODUCT_ID = O.PRODUCT_ID
GROUP BY P.PRODUCT_ID, P.PRODUCT_NAME
ORDER BY TOTAL_QUANTITY_SOLD DESC;

-- Product Sales Amount
SELECT P.PRODUCT_ID,
       P.PRODUCT_NAME,
       SUM(O.QUANTITY) AS TOTAL_QUANTITY_SOLD,
       SUM(O.QUANTITY * P.PRICE) AS TOTAL_SALES
FROM PRODUCT P
JOIN ORDERS O
  ON P.PRODUCT_ID = O.PRODUCT_ID
GROUP BY P.PRODUCT_ID, P.PRODUCT_NAME
ORDER BY TOTAL_SALES DESC;

-- 3. Combined Business Sales Report
SELECT C.CUSTOMER_ID,
       C.CUSTOMER_NAME,
       O.ORDER_ID,
       P.PRODUCT_ID,
       P.PRODUCT_NAME,
       O.QUANTITY,
       P.PRICE,
       (O.QUANTITY * P.PRICE) AS SUBTOTAL
FROM CUSTOMERS C
JOIN ORDERS O
  ON C.CUSTOMER_ID = O.CUSTOMER_ID
JOIN PRODUCT P
  ON O.PRODUCT_ID = P.PRODUCT_ID
ORDER BY O.ORDER_ID;
